"""`brief:fill` 프롬프트 조립. 모델 클라이언트와 분리해 둡니다.

⚠️ **FastAPI 도 모델 SDK 도 import 하지 않습니다.** `render_prompt` 와 같은 이유입니다 -
프롬프트가 맞는지는 호출 없이 확인할 수 있어야 하고, 한 번 부를 때마다 요금이 나가는 구조에서
문장을 고칠 때마다 API 를 때려야 한다면 아무도 프롬프트를 손보지 않게 됩니다.

⚠️ 업로드 파일도 여기 들어오지 않습니다. 사진은 `brief_fill` 이 바이트로 읽어 붙이고, 이 모듈은
글자만 만듭니다 - `service_schemas.BriefFillRequest` 를 만지는 순간 이 파일이 Starlette 에
묶여 웹 프레임워크 없이 못 부르게 됩니다.
"""

VERSION = "brief-fill-v0"
"""프롬프트 판. 지표를 비교하려면 어느 프롬프트로 뽑은 결과인지가 남아야 합니다
(생성_파이프라인 4절). 문구를 고치면 이 값도 올리세요 - **판을 올리지 않은 프롬프트 변경은
그 이전 실측을 전부 무효로 만듭니다.**"""

SYSTEM = """당신은 광고 브리프의 빈 칸을 채우는 분석기입니다.

주어진 제품 사진과 글에서 '카테고리'와 '주 타겟'을 추론합니다. 광고 문구를 쓰지 않습니다.

[규칙]
1. 사진과 아래 제품 정보에서 읽히는 것만 씁니다. 브랜드, 효능, 수상 이력을 추측하지 마세요.
2. 둘 다 짧은 명사구로 씁니다. 문장이나 설명을 붙이지 마세요.
3. 사진과 글만으로 판단이 서지 않으면 **지어내지 말고** 아래 거절 형식으로 답합니다.

[출력]
JSON 하나만 출력합니다. 설명도 머리말도 붙이지 마세요.

판단이 설 때:
{"category": "<카테고리>", "target": "<주 타겟>"}

판단이 서지 않을 때:
{"needsInput": {"reason": "<무엇이 부족한지 사용자에게 보여 줄 한 문장>"}}"""
"""역할 지시 + 근거 제한 + 출력 형식.

⚠️ **거절 갈래가 프롬프트에 있는 것이 핵심입니다.** 이 모듈이 답을 강요하면 모델은 사진이
무엇인지 몰라도 그럴듯한 카테고리를 하나 만들어 냅니다. 그 값은 브리프에 저장되어 나중에
카피의 근거처럼 읽히는데, 정작 아무 근거도 없습니다 (기획서 9.3, 생성_파이프라인 5.2절).
"""


def build_user(product_name: str, selling_point: str, note: str | None) -> str:
    """사진과 함께 보낼 글. 사진은 호출부가 별도 파트로 붙입니다.

    ⚠️ 빈 문자열은 "비어 있음"이고 키 생략은 "해당 없음"입니다 (계약 3절). 둘 다 프롬프트에
    넣지 않지만 `or` 한 번으로 합치지는 않습니다 - `render_prompt._common_head` 와 같은
    이유로, 나중에 의미가 갈릴 때 여기가 먼저 틀립니다.
    """
    lines = [f"제품명: {product_name}", f"소구점: {selling_point}"]
    if note:
        lines.append(f"자유 메모: {note}")
    return "\n".join(lines)
